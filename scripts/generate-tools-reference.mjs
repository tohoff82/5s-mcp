#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TOOL_REGISTRATIONS, createRegisteredTools } from '../src/mcp-server/tool-registry.js';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(repoRoot, 'docs/04-TOOLS-REFERENCE.md');
const EXPECTED_TOOL_COUNT = 12;
const LAST_VERIFIED_COMMIT = '04d75cabcef5da03a21c22982dbe45dacfa6844c';

export function deriveTools() {
  const runtimeTools = createRegisteredTools();
  if (runtimeTools.length !== TOOL_REGISTRATIONS.length) {
    throw new Error('runtime tool and registry metadata counts differ');
  }
  if (runtimeTools.length !== EXPECTED_TOOL_COUNT) {
    throw new Error(`registered tool count is ${runtimeTools.length}; expected ${EXPECTED_TOOL_COUNT}`);
  }

  const tools = runtimeTools.map((tool, index) => ({
    ...tool,
    source: TOOL_REGISTRATIONS[index].source,
    group: TOOL_REGISTRATIONS[index].group,
    lifecycle: TOOL_REGISTRATIONS[index].lifecycle,
    policyPath: TOOL_REGISTRATIONS[index].policyPath
  }));
  const names = new Set(tools.map(tool => tool.name));
  if (names.size !== tools.length) throw new Error('duplicate registered tool names detected');

  for (const tool of tools) {
    if (!tool.name || !tool.description || tool.inputSchema?.type !== 'object') {
      throw new Error(`incomplete runtime definition for ${tool.name || tool.source}`);
    }
    for (const hint of ['readOnlyHint', 'destructiveHint', 'idempotentHint']) {
      if (typeof tool.annotations?.[hint] !== 'boolean') {
        throw new Error(`missing ${hint} annotation for ${tool.name}`);
      }
    }
  }
  return tools;
}

const yesNo = value => value ? 'yes' : 'no';

function modes(tool) {
  for (const selector of ['action', 'target']) {
    const values = tool.inputSchema?.properties?.[selector]?.enum;
    if (Array.isArray(values)) return { selector, values };
  }
  return { selector: null, values: [] };
}

export function renderToolsReference(tools = deriveTools()) {
  const groups = new Map();
  for (const tool of tools) groups.set(tool.group, [...(groups.get(tool.group) ?? []), tool]);
  const readOnly = tools.filter(tool => tool.annotations.readOnlyHint).length;
  const destructive = tools.filter(tool => tool.annotations.destructiveHint).length;
  const lines = [
    '---',
    'document_id: 5S-DOC-TOOLS',
    'authority: generated',
    'status: current',
    'source_of_truth: src/mcp-server/tool-registry.js and tool factories',
    `last_verified_commit: ${LAST_VERIFIED_COMMIT}`,
    'audience: [user, operator, maintainer, agent]',
    '---',
    '',
    '# Tool reference',
    '',
    '<!-- GENERATED by scripts/generate-tools-reference.mjs. DO NOT EDIT. -->',
    '',
    `The runtime registry contains **${tools.length} registered and ${new Set(tools.map(tool => tool.name)).size} unique tools**: ${readOnly} read-only tools, ${destructive} destructive-capable tools, and ${tools.length - readOnly - destructive} mixed non-destructive tools. Ordering follows \`TOOL_REGISTRATIONS\` in \`src/mcp-server/tool-registry.js\`.`,
    '',
    'Annotations are conservative tool-level hints. A mixed tool is classified by its most powerful action; annotations do not grant authorization. Required inputs and complete JSON Schemas below are generated from the same runtime objects returned by the MCP list-tools handler.',
    '',
    'See [operator guidance](05-OPERATOR-GUIDE.md), [security boundaries](06-SECURITY-AND-TRUST-BOUNDARIES.md), and the [maintenance lifecycle](07-MAINTENANCE-LIFECYCLE/README.md).',
    ''
  ];

  for (const [group, groupTools] of groups) {
    lines.push(`## ${group} (${groupTools.length})`, '');
    for (const tool of groupTools) {
      const selector = modes(tool);
      const required = tool.inputSchema.required ?? [];
      lines.push(
        `### \`${tool.name}\``,
        '',
        tool.description,
        '',
        `- Classification: read-only=${yesNo(tool.annotations.readOnlyHint)}; destructive=${yesNo(tool.annotations.destructiveHint)}; idempotent=${yesNo(tool.annotations.idempotentHint)}.`,
        `- Required inputs: ${required.length ? required.map(input => `\`${input}\``).join(', ') : 'none'}.`,
        `- ${selector.selector ? `Selector \`${selector.selector}\`` : 'Modes'}: ${selector.values.length ? selector.values.map(value => `\`${value}\``).join(', ') : 'not enumerated'}.`,
        `- Lifecycle: ${tool.lifecycle}.`,
        `- Policy path: ${tool.policyPath}`,
        `- Source: \`${tool.source}\`.`,
        '',
        '<details>',
        '<summary>Runtime input schema</summary>',
        '',
        '```json',
        JSON.stringify(tool.inputSchema, null, 2),
        '```',
        '',
        '</details>',
        ''
      );
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

export function checkOrWrite({ check = false } = {}) {
  const tools = deriveTools();
  const rendered = renderToolsReference(tools);
  if (check) {
    const current = readFileSync(outputPath, 'utf8');
    if (current !== rendered) throw new Error('docs/04-TOOLS-REFERENCE.md is stale; run npm run docs:generate');
  } else {
    writeFileSync(outputPath, rendered);
  }
  return tools;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const check = process.argv.includes('--check');
    const tools = checkOrWrite({ check });
    process.stdout.write(`${check ? 'verified' : 'generated'} ${tools.length} unique tools\n`);
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  }
}
